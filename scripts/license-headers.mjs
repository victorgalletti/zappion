#!/usr/bin/env node
// SPDX-License-Identifier: AGPL-3.0-only
//
// Adds the SPDX license line to Zappion's source files, or checks that every one has it.
//   node scripts/license-headers.mjs          add the line where it is missing
//   node scripts/license-headers.mjs --check  list the files without it and exit 1 (CI)
//
// Covered: web/, windows/, signup/, scripts/, and in api/ only Zappion's own files (`zappion_*` and the
// MCP Apps screens). The rest of api/ is open-bsp's public-domain code, kept as close to upstream as
// possible; the root LICENSE covers it as part of Zappion.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const SPDX = "SPDX-License-Identifier: AGPL-3.0-only";

const STYLES = {
  line: (t) => `// ${t}`,
  hash: (t) => `# ${t}`,
  sql: (t) => `-- ${t}`,
  block: (t) => `/* ${t} */`,
  html: (t) => `<!-- ${t} -->`,
};

const BY_EXTENSION = {
  ts: "line", tsx: "line", js: "line", mjs: "line", mts: "line", cs: "line",
  ps1: "hash", py: "hash", sh: "hash",
  sql: "sql",
  css: "block",
  html: "html",
};

const INCLUDE = [/^web\//, /^windows\//, /^signup\//, /^scripts\//, /^api\/.*zappion_[^/]*$/, /^api\/supabase\/functions\/mcp\/ui\//];
const EXCLUDE = [
  /^web\/public\//, // third-party builds (see THIRD-PARTY-NOTICES.md)
  /^web\/next-env\.d\.ts$/, // generated by Next.js
  /\.json$/,
];

function covered(path) {
  const extension = path.split(".").pop();
  return BY_EXTENSION[extension] && INCLUDE.some((r) => r.test(path)) && !EXCLUDE.some((r) => r.test(path));
}

// Where the line goes: after a shebang, an HTML doctype or a Python encoding cookie, otherwise first.
function insertAt(lines) {
  let i = 0;
  if (lines[0]?.startsWith("#!")) i = 1;
  if (/^<!doctype/i.test(lines[0] ?? "")) i = 1;
  if (/coding[:=]/.test(lines[i] ?? "") && lines[i].startsWith("#")) i += 1;
  return i;
}

const check = process.argv.includes("--check");
const root = execFileSync("git", ["rev-parse", "--show-toplevel"], { encoding: "utf8" }).trim();
const files = execFileSync("git", ["ls-files", "-z"], { cwd: root, encoding: "utf8" })
  .split("\0")
  .filter((path) => path && covered(path));

const missing = [];
for (const path of files) {
  const full = `${root}/${path}`;
  const raw = readFileSync(full, "utf8");
  if (raw.slice(0, 600).includes(SPDX)) continue;
  missing.push(path);
  if (check) continue;

  const bom = raw.startsWith("﻿") ? "﻿" : "";
  const eol = raw.includes("\r\n") ? "\r\n" : "\n";
  const lines = raw.slice(bom.length).split(/\r?\n/);
  const style = STYLES[BY_EXTENSION[path.split(".").pop()]];
  lines.splice(insertAt(lines), 0, style(SPDX));
  writeFileSync(full, bom + lines.join(eol));
}

if (check) {
  if (missing.length) {
    console.error(`${missing.length} file(s) without "${SPDX}":\n  ${missing.join("\n  ")}`);
    console.error("Run: node scripts/license-headers.mjs");
    process.exit(1);
  }
  console.log(`All ${files.length} covered files have the license line.`);
} else {
  console.log(`Added the license line to ${missing.length} of ${files.length} files.`);
}
